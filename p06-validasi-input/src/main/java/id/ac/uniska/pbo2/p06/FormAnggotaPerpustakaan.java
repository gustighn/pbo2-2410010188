    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
        boolean npmValid = periksaNpm();
        boolean namaValid = periksaNama();
        boolean emailValid = periksaEmail();
        boolean hpValid = periksaHp();

        int jumlahError = 0;

        if (!npmValid) {
            jumlahError++;
        }
        if (!namaValid) {
            jumlahError++;
        }
        if (!emailValid) {
            jumlahError++;
        }
        if (!hpValid) {
            jumlahError++;
        }

        if (jumlahError > 0) {

            JOptionPane.showMessageDialog(
                    this,
                    jumlahError + " isian perlu diperbaiki.",
                    "Validasi Input",
                    JOptionPane.WARNING_MESSAGE
            );

            if (!npmValid) {
                npmField.requestFocusInWindow();
            } else if (!namaValid) {
                namaField.requestFocusInWindow();
            } else if (!emailValid) {
                emailField.requestFocusInWindow();
            } else if (!hpValid) {
                hpField.requestFocusInWindow();
            }

            return;
        }

        tampilkanRingkasan();
    }//GEN-LAST:event_daftarButtonActionPerformed

