    private void saring() {
        String kata = cariField.getText().trim();

        if (kata.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            sorter.setRowFilter(
                    RowFilter.regexFilter(
                            "(?i)" + Pattern.quote(kata),
                            0, 1, 2
                    )
            );
        }

        perbaruiStatus();
    }

    private int barisTerpilih() {
        int barisTampilan = bukuTable.getSelectedRow();

        if (barisTampilan < 0) {
            return -1;
        }

        return bukuTable.convertRowIndexToModel(barisTampilan);
    }

    private void tambah() {
        Buku baru = new DialogBuku(
                this,
                "Tambah Buku",
                null
        ).tampilkan();

        if (baru != null) {
            try {
                model.tambah(baru);
                perbaruiStatus();

            } catch (IllegalArgumentException e) {
                JOptionPane.showMessageDialog(
                        this,
                        "Kode buku sudah digunakan!",
                        "Gagal Menambahkan Buku",
                        JOptionPane.WARNING_MESSAGE
                );
            }
        }
    }

    private void ubah() {
        int baris = barisTerpilih();

        if (baris < 0) {
            return;
        }

        Buku hasil = new DialogBuku(
                this,
                "Ubah Buku",
                model.getBuku(baris)
        ).tampilkan();

        if (hasil != null) {
            boolean berhasil = model.ubah(
                    model.getBuku(baris).getKode(),
                    hasil
            );

            if (berhasil) {
                perbaruiStatus();
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "Kode buku sudah digunakan oleh buku lain!",
                        "Gagal Mengubah Buku",
                        JOptionPane.WARNING_MESSAGE
                );
            }
        }
    }

    private void hapus() {
        int baris = barisTerpilih();

        if (baris < 0) {
            return;
        }

        String judul = model.getBuku(baris).getJudul();

        int jawab = JOptionPane.showConfirmDialog(
                this,
                "Hapus buku \"" + judul + "\"?",
                "Konfirmasi Hapus",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
        );

        if (jawab == JOptionPane.YES_OPTION) {
            model.hapus(baris);
            perbaruiStatus();
        }
    }

